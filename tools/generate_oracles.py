"""Original synthetic fixtures generated through laspy 2.6.1, numpy 2.2.6.
No external lidar data, source code or upstream tests are copied.
Run then moon fmt; CI compares the generated, formatted file byte-for-byte.
"""
import datetime
import io
import json
import uuid
from types import SimpleNamespace
from pathlib import Path
import laspy
import numpy as np

assert laspy.__version__ == "2.6.1"
assert np.__version__ == "2.2.6"
ROOT = Path(__file__).resolve().parents[1]

def binary(data):
    sink = io.BytesIO()
    data.write(sink)
    return sink.getvalue()

def literal(raw):
    # One exact fixture constant; not production LOC.
    return 'b"' + ''.join('\\x%02x' % b for b in raw) + '"'

def main():
    rng = np.random.default_rng(20261111)
    lines = ['// Generated by tools/generate_oracles.py; original deterministic data.']
    cases = []
    for fmt in [0, 1, 2, 3, 6, 7, 8]:
        for minor in ([2, 4] if fmt < 6 else [4]):
            h = laspy.LasHeader(point_format=fmt, version=f"1.{minor}")
            h.scales = np.array([0.01, 0.02, 0.05])
            h.offsets = np.array([1000., -500., 2.5])
            h.creation_date = datetime.date(2026, 11, 11)
            h.system_identifier = 'oracle'
            h.generating_software = 'laspy 2.6.1'
            h.uuid = uuid.UUID('01234567-89ab-cdef-0123-456789abcdef')
            h.extra_vlr_bytes = b'opaque-gap'
            h.vlrs.append(laspy.VLR(user_id='reference', record_id=19, description='opaque', record_data=b'\x00\xffsample'))
            las = laspy.LasData(h)
            las.add_extra_dim(laspy.ExtraBytesParams(name='tag', type=np.dtype('u2')))
            n = 32
            las.X = rng.integers(-2000000, 2000000, n, dtype=np.int32)
            las.Y = rng.integers(-2000000, 2000000, n, dtype=np.int32)
            las.Z = rng.integers(-2000000, 2000000, n, dtype=np.int32)
            las.intensity = rng.integers(0, 65536, n, dtype=np.uint16)
            cap = 5 if fmt < 6 else 15
            totals = rng.integers(1, cap + 1, n, dtype=np.uint8)
            las.number_of_returns = totals
            las.return_number = np.array([rng.integers(1, int(t)+1) for t in totals], dtype=np.uint8)
            las.classification = rng.integers(0, 32 if fmt < 6 else 256, n, dtype=np.uint8)
            for name in ['synthetic','key_point','withheld','scan_direction_flag','edge_of_flight_line']:
                setattr(las, name, rng.integers(0, 2, n, dtype=np.uint8))
            if fmt >= 6:
                las.overlap = rng.integers(0, 2, n, dtype=np.uint8)
                las.scanner_channel = rng.integers(0, 4, n, dtype=np.uint8)
                las.scan_angle = rng.integers(-30000, 30001, n, dtype=np.int16)
            else:
                las.scan_angle_rank = rng.integers(-90, 91, n, dtype=np.int8)
            las.user_data = rng.integers(0, 256, n, dtype=np.uint8)
            las.point_source_id = rng.integers(0, 65536, n, dtype=np.uint16)
            las.tag = rng.integers(0, 65536, n, dtype=np.uint16)
            if fmt in [1, 3, 6, 7, 8]:
                las.gps_time = np.arange(n, dtype=np.float64)*0.25+12345.5
            if fmt in [2, 3, 7, 8]:
                for name in ['red','green','blue']:
                    setattr(las, name, rng.integers(0, 65536, n, dtype=np.uint16))
            if fmt == 8:
                las.nir = rng.integers(0, 65536, n, dtype=np.uint16)
            raw = binary(las)
            lines += [f'test "laspy oracle LAS1.{minor} format {fmt} 32 records" {{',
                      f'  let raw = {literal(raw)}', '  let d = try { decode(raw) } catch { Invalid(m) => fail(m); e => raise e }',
                      '  assert_eq(d.points.length(),32)', '  assert_eq(d.gap,b"opaque-gap")',
                      '  assert_eq(d.audit().issues.length(),0)']
            for i in range(n):
                p = SimpleNamespace(**{name: np.asarray(las[name])[i].item() for name in las.point_format.dimension_names})
                flags = int(p.synthetic)+2*int(p.key_point)+4*int(p.withheld)+(8*int(p.overlap) if fmt >= 6 else 0)
                fields = dict(x=int(p.X),y=int(p.Y),z=int(p.Z),intensity=int(p.intensity),return_number=int(p.return_number),returns=int(p.number_of_returns),classification=int(p.classification),flags=flags,scanner_channel=int(p.scanner_channel) if fmt>=6 else 0,scan_direction=str(bool(p.scan_direction_flag)).lower(),edge=str(bool(p.edge_of_flight_line)).lower(),scan_angle=int(p.scan_angle if fmt>=6 else p.scan_angle_rank),user_data=int(p.user_data),source_id=int(p.point_source_id),gps_time=f'Some({float(p.gps_time)})' if fmt in [1,3,6,7,8] else 'None',rgb=f'Some(({int(p.red)},{int(p.green)},{int(p.blue)}))' if fmt in [2,3,7,8] else 'None',nir=f'Some({int(p.nir)})' if fmt==8 else 'None',extra=literal(int(p.tag).to_bytes(2,'little')))
                lines.append('  assert_eq(d.points[%d], Point::{%s})' % (i, ','.join(f'{k}: {v}' for k,v in fields.items())))
            lines += ['  assert_eq(encode(d),raw)',
                      '  let changed = d.with_points(d.points.map(p => { ..p, x: p.x+7, intensity: 65535-p.intensity }))']
            las.X = np.asarray(las.X) + 7
            las.intensity = 65535 - np.asarray(las.intensity)
            changed = binary(las)
            lines += [f'  assert_eq(encode(changed),{literal(changed)})', '}']
            cases.append({'minor':minor,'format':fmt,'records':n,'bytes':len(raw)})
    (ROOT/'reference_wbtest.mbt').write_text('\n'.join(lines)+'\n',encoding='utf-8')
    (ROOT/'tools/oracle-manifest.json').write_text(json.dumps({'seed':20261111,'laspy':'2.6.1','numpy':'2.2.6','cases':cases},indent=2)+'\n',encoding='utf-8')
    print(f'{len(cases)} documents; {sum(c["records"] for c in cases)} independently generated records; read + changed-write assertions')

if __name__ == '__main__':
    main()
